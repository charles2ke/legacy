#!/usr/bin/env node
// Writes .github/CODEOWNERS from the "admins" field of each profile, so the
// people who own a profile are the ones who must approve changes to it —
// including changes to its visibility. Run `npm run codeowners` after adding or
// changing an "admins" list; CI runs `npm run codeowners:check` to catch drift.
//
// CODEOWNERS only has an effect once a maintainer turns on branch protection
// with "Require review from Code Owners"; see docs/VISIBILITY.md.

import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

import { GITHUB_USERNAME_PATTERN, MAX_LENGTHS, SLUG_PATTERN } from '../assets/js/profile-schema.js';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const profilesDir = path.join(repoRoot, 'profiles');
const codeownersPath = path.join(repoRoot, '.github', 'CODEOWNERS');

const HEADER = [
  '# Generated by `npm run codeowners` from the "admins" field of each profile.',
  '# Do not edit by hand: change the profile and run the script again.',
  '#',
  '# Each line makes the people who own a profile the required reviewers for it,',
  '# so nobody else can change their story — or its visibility — without them.',
  '# This only takes effect once a maintainer enables branch protection with',
  '# "Require review from Code Owners". See docs/VISIBILITY.md.',
];

// The maintainers who own this file and the machinery that writes it. Without
// these rules a pull request could simply delete the profile rules below — or
// change the script that produces them — and no profile owner would have to
// approve it. They are written last because the last matching rule wins.
export const MAINTAINERS = ['charles2ke'];

const FOOTER = [
  '',
  '# Who may change who owns what: this file, the workflows that check it and the',
  '# scripts that manage them are owned by the maintainers, so the rules above cannot',
  '# be weakened without them.',
  ...['/.github/', '/scripts/'].map(
    (target) => `${target} ${MAINTAINERS.map((maintainer) => `@${maintainer}`).join(' ')}`,
  ),
];

/** Admins of one profile, de-duplicated case insensitively, order preserved. */
function adminsOf(profile) {
  const admins = Array.isArray(profile?.admins) ? profile.admins : [];
  const seen = new Set();
  const result = [];
  for (const admin of admins) {
    if (typeof admin !== 'string') continue;
    if (!GITHUB_USERNAME_PATTERN.test(admin) || admin.length > MAX_LENGTHS.admin) continue;
    const key = admin.toLowerCase();
    if (seen.has(key)) continue;
    seen.add(key);
    result.push(admin);
  }
  return result;
}

/**
 * Renders the whole file. Entries are sorted by slug so the output only changes
 * when the profiles do.
 *
 * Every part of a line is checked here rather than trusted from the caller. Both
 * the slug and the admin names end up in a file that decides who may approve
 * changes, and a newline in either would write rules nobody asked for — so an
 * entry whose slug is not a plain slug is dropped, exactly as an admin whose
 * name is not a plain username is.
 * @param {{ slug: string, profile: unknown }[]} entries
 */
export function renderCodeowners(entries) {
  const lines = [...HEADER, ''];
  const owned = entries
    .filter((entry) => typeof entry?.slug === 'string' && SLUG_PATTERN.test(entry.slug))
    .map((entry) => ({ slug: entry.slug, admins: adminsOf(entry.profile) }))
    .filter((entry) => entry.admins.length > 0)
    .sort((a, b) => a.slug.localeCompare(b.slug));

  if (owned.length === 0) {
    lines.push('# No profile currently names an admin.');
  }
  for (const entry of owned) {
    lines.push(`/profiles/${entry.slug}.json ${entry.admins.map((admin) => `@${admin}`).join(' ')}`);
  }
  lines.push(...FOOTER);
  return `${lines.join('\n')}\n`;
}

async function readEntries(dir = profilesDir) {
  const files = (await readdir(dir))
    .filter((file) => file.endsWith('.json'))
    .filter((file) => file !== 'index.json' && !file.startsWith('_'))
    .sort();

  const entries = [];
  for (const file of files) {
    entries.push({
      slug: file.replace(/\.json$/, ''),
      profile: JSON.parse(await readFile(path.join(dir, file), 'utf8')),
    });
  }
  return entries;
}

/** @returns {{ upToDate: boolean, expected: string }} */
export async function checkCodeowners(dir = profilesDir, file = codeownersPath) {
  const expected = renderCodeowners(await readEntries(dir));
  let actual = '';
  try {
    actual = await readFile(file, 'utf8');
  } catch {
    actual = '';
  }
  return { upToDate: actual === expected, expected };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes('--check')) {
    const { upToDate } = await checkCodeowners();
    if (!upToDate) {
      console.error('.github/CODEOWNERS is out of date. Run `npm run codeowners` and commit the result.');
      process.exit(1);
    }
    console.log('.github/CODEOWNERS is up to date.');
  } else {
    const expected = renderCodeowners(await readEntries());
    await writeFile(codeownersPath, expected);
    console.log('Wrote .github/CODEOWNERS.');
  }
}
